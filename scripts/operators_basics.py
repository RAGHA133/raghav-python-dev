# scripts/operators_basics.py

a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

print("\nComparison:")
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)

print("\nAssignment:")
a += 5
print("a += 5:", a)
a *= 2
print("a *= 2:", a)

print("\nLogical:")
x = True
y = False
print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)
